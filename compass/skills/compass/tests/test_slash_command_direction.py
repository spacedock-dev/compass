"""A Claude Code slash command is a reader direction, and a harness control is not (DRC-4764).

A reader who directs a session with `/pr-review-response 1287 …` or `/review` gave a direction,
and before this the observed record dropped it: the record parsed as the reader's message, but
`project_context._semantic_line` skips every line that opens with `<`, and the command arrives
wholly in `<command-message>`, `<command-name>` and `<command-args>` tags. A reading could then
call work the reader asked for a departure, and the page did not list it as a later direction.

The fixtures are hand-written in the shapes measured over the local Claude store on 2026-10-01,
counts only: a prompt command (a skill, or a built-in that expands into a prompt) leads with
`<command-message>` and is followed by an `isMeta` record holding the expanded prompt; a local
command the harness runs itself (`/clear`, `/login`, `/compact`) leads with `<command-name>`,
usually after an `isMeta` `<local-command-caveat>` record, and is followed by
`<local-command-stdout>`. Every text here is placeholder prose, and the one credential shape is
the documented `AKIAIOSFODNN7EXAMPLE`.
"""

